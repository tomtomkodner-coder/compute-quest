import { launch, ctxFor, watch, toMenu, asyncClick, waitWorld, until, errs, sleep } from "./lib.mjs";
const b = await launch();
const ctx = await ctxFor(b);
const A = await ctx.newPage(); watch(A, "A");
await toMenu(A);
await A.click("text=Create Server");
await A.fill("input >> nth=0", "Alice");
await A.fill("input >> nth=1", "Tom Server");
await A.fill("input >> nth=2", "abc");
await A.evaluate(() => { const bs = [...document.querySelectorAll("button")].filter((x) => x.textContent.trim() === "Create Server"); setTimeout(() => bs[bs.length - 1].click(), 0); });
await waitWorld(A);
console.log("A in", await A.evaluate(() => [window.__meccha.net.kind, window.__meccha.net.code, window.__meccha.isHost()]));
const B = await ctx.newPage(); watch(B, "B");
await toMenu(B);
await B.click("text=Find Server");
await B.fill("input >> nth=0", "Bob");
await B.click("text=Search Public Servers");
await sleep(2500);
console.log("B list", await B.evaluate(() => [...document.querySelectorAll("button")].filter((x) => x.textContent.trim() === "Join").length), await B.evaluate(() => document.body.innerText.match(/Tom Server[^\n]*/)?.[0]));
await asyncClick(B, "Join"); await sleep(1500);
console.log("B note (no pw)", await B.evaluate(() => document.body.innerText.includes("Wrong password")));
await B.fill("input >> nth=2", "abc");
await asyncClick(B, "Join");
await waitWorld(B);
const r = await until([A, B], () => { const e = window.__meccha; return e.players.size >= 2 ? [...e.players.values()].map((p) => p.name).join(",") : ""; }, null, 60000, "sync");
console.log("players", r);
console.log("errors", errs.slice(0, 6));
await b.close();
